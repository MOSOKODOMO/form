const {test} = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const home = fs.readFileSync('dist/index.html', 'utf8')

test('window comparison aligns the glass brief without inventing matched delivered prices', () => {
  assert.match(home, /6 mm Low-E \/ 12 mm cavity \/ 6 mm toughened double glazing/)
  assert.match(home, /A\$900\/m² × 1\.44 m²/)
  assert.equal((800 / 0.7102).toFixed(2), '1126.44')
  assert.match(home, /Interstate quote required/)
  assert.match(home, /Not an exact unit quote/)
  assert.doesNotMatch(home, /US\$800|Stegbar|Melbourne market|XN Windows|Florida/)
  const cards = [...home.matchAll(/<article class="quote-card">([\s\S]*?)<\/article>/g)].map((match) => match[1])
  assert.equal(cards.length, 3)
  assert.deepEqual(cards.map((card) => card.match(/<h3>(.*?)<\/h3>/)[1]), ['SMG Glass', 'Superhouse', 'uPVC.com.au'])
  assert.match(cards[0], /OPTION 01[\s\S]*THAILAND/)
  assert.match(cards[1], /OPTION 02[\s\S]*CHINA/)
  assert.match(cards[2], /OPTION 03[\s\S]*LOCAL AUSTRALIA/)

  assert.match(cards[0], /A\$212–403\/m²/)
  assert.match(cards[0], /(?:indicative|guide)/i)
  assert.match(cards[0], /(?:not a complete|not a framed|glass.only)/i)
  assert.match(cards[0], /(?:quote required|to quote|confirm in quote)/i)
  assert.match(cards[0], /https:\/\/www\.smg-con\.co\.th\/news_detail\.php\?id=64/)

  assert.match(cards[1], /A\$1,126\.44/)
  assert.match(cards[1], /door.to.door[\s\S]*included/i)
  assert.match(cards[1], /<dt>Door delivery<\/dt><dd>Included · door-to-door<\/dd>/)
  assert.match(cards[1], /(?:GST|duty|import)[\s\S]*(?:unconfirmed|not confirmed|to be confirmed|confirm)/i)
  assert.doesNotMatch(cards[1], /Requote required|not Australia/)

  assert.match(cards[2], /A\$1,296/)
  assert.match(cards[2], /CALCULATED SUPPLY BENCHMARK/)
  assert.doesNotMatch(cards.join(''), /(?:US\$|USD\s*\d|THB\s*\d|฿)/)

  const labels = cards.map((card) => [...card.matchAll(/<dt>(.*?)<\/dt>/g)].map((match) => match[1]))
  assert.equal(labels[0][0], 'Supply scope')
  assert.deepEqual(labels[0], labels[1])
  assert.deepEqual(labels[1], labels[2])
  assert.deepEqual(cards.map((card) => card.match(/<dt>Supply scope<\/dt><dd>(.*?)<\/dd>/)[1]), [
    'Glass only · not a window', 'Complete window', 'Complete-window benchmark',
  ])
  assert.match(home, /not like-for-like delivered totals/)
  assert.match(home, /Country order is not a price or quality ranking/)
  assert.match(home, /does not establish equal quality/)
})
